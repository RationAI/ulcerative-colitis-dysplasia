"""HunCRC cohort reader.

One slide per patient (.mrxs, 001-200), so case_id == slide_id. Per-tile label
sets live in the TCIA ML-dataset, one <NNN>_labels.csv per slide, split across
zoom parts. Annotations are the grid-cell JSONs produced by
scripts/make_huncrc_annotations.py -- one <NNN>.json per slide under
config.dataset.annot_path.
"""

import re
from pathlib import Path

import pandas as pd
from omegaconf import DictConfig

from .common import get_df

#: Per-tile label sets live one dir per case under each zoom part:
#: ML_dataset/<zoom_part>/<NNN>/<NNN>_labels.csv
TILES_GLOB = "*/[0-9][0-9][0-9]/[0-9][0-9][0-9]_labels.csv"


def extract_case_id(stem: str) -> str:
    #: HunCRC has one slide per patient, so case_id == slide_id. The column is
    #: kept rather than dropped so split_dataset.py's group-by-case_id works.
    return stem


def get_tile_df(tiles_path: Path) -> pd.DataFrame:
    """One row per slide, keyed by slide_id, pointing at its <NNN>_labels.csv.

    No regex filter here, unlike the slides: TILES_GLOB already pins the exact
    3-digit case dir and 3-digit label filename, and it cannot share a pattern
    with the *.mrxs names.

    Cases are split across zoom_1_partA/B/C + zoom_2, so every part is
    searched. A slide can have a label set in both a zoom_1 part and zoom_2,
    so zoom_1 (level 1) wins and zoom_2 only fills the gaps.
    """
    best: dict[str, tuple[int, str]] = {}
    for labels_path in sorted(tiles_path.glob(TILES_GLOB)):
        slide_id = labels_path.stem.removesuffix("_labels")
        #: .../<zoom_part>/<NNN>/<NNN>_labels.csv -- the part is the grandparent.
        part = labels_path.parent.parent.name
        priority = 0 if part.startswith("zoom_1") else 1
        if slide_id not in best or priority < best[slide_id][0]:
            best[slide_id] = (priority, str(labels_path.absolute()))

    df = pd.DataFrame(
        [
            {"slide_id": slide_id, "tiles_path": path}
            for slide_id, (_, path) in best.items()
        ]
    )
    if df.empty:
        return pd.DataFrame(columns=["slide_id", "tiles_path"]).set_index("slide_id")
    return df.set_index("slide_id")


def create_dataset(config: DictConfig) -> tuple[pd.DataFrame, list[str]]:
    """Build the dataset for the HunCRC cohort.

    Returns (dataset_df indexed by slide_id with [case_id, slide_path,
    tiles_path, annot_path], missing tiles) -- same contract as the other
    readers.
    """
    pattern = re.compile(config.dataset.regex_pattern)

    slides_df = get_df(
        Path(config.dataset.slides_path), pattern, key="slide", ext="*.mrxs",
        extract_case_id=extract_case_id,
    )
    tiles_df = get_tile_df(Path(config.dataset.tiles_path))

    #: Left join keyed on slides, so a slide without a label set survives as
    #: NaN and becomes the missing-tiles QC signal instead of silently
    #: vanishing from the CSV.
    dataset_df = slides_df.join(tiles_df, how="left")

    missing_tiles = dataset_df[dataset_df["tiles_path"].isna()].index.to_list()
    print(
        f"[create_dataset] {len(dataset_df)} slides, "
        f"{len(missing_tiles)} without per-tile labels"
    )

    #: Tiling looks the annotation JSONs up through this column
    #: (preprocessing/tiling.py add_annot_path); they live one per slide under
    #: config.dataset.annot_path, generated by
    #: scripts/make_huncrc_annotations.py.
    dataset_df["annot_path"] = dataset_df.index.map(
        lambda slide_id: f"{config.dataset.annot_path}/{slide_id}.json"
    )

    dataset_df = dataset_df[["case_id", "slide_path", "tiles_path", "annot_path"]]

    return dataset_df, missing_tiles
